-- =====================================================================
-- experiments/01_concurrency.sql — дослідження конкурентного доступу
-- та блокувань рядків (п. 5.7 методичних рекомендацій, с. 18)
-- Виконується у ДВОХ незалежних підключеннях (Сеанс А та Сеанс Б).
-- =====================================================================

-- ---------------------------------------------------------------------
-- СЕАНС А (перше вікно psql / консолі):
-- Блокує рядок наряду id=1 для оновлення і залишає транзакцію відкритою.
-- ---------------------------------------------------------------------
BEGIN;
SELECT id, order_number, status, planned_date
FROM avia_mro.work_orders
WHERE id = 1
    FOR UPDATE;

-- (Тримаємо транзакцію відкритою, поки у Сеансі Б виконується UPDATE)
-- Після фіксації очікування / тайм-ауту у Сеансі Б виконуємо відкат:
ROLLBACK;


-- ---------------------------------------------------------------------
-- СЕАНС Б (друге вікно psql / консолі):
-- Намагається змінити той самий рядок із обмеженням очікування 30 с.
-- Очікуваний результат: блокування до завершення Сеансу А або
-- помилка ERROR: canceling statement due to lock timeout.
-- ---------------------------------------------------------------------
BEGIN;
SET LOCAL lock_timeout = '30s';
UPDATE avia_mro.work_orders
SET planned_date = planned_date + 1
WHERE id = 1;
ROLLBACK;